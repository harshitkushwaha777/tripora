from pydantic import BaseModel, Field
from typing import Optional, List, Dict, Any
from backend.app.schemas.trip import ActivityBase, DayBase

class GenerateItineraryRequest(BaseModel):
    destination: str = Field(..., min_length=2, max_length=150)
    origin: Optional[str] = Field(None, max_length=150)
    start_date: str = Field(..., pattern=r"^\d{4}-\d{2}-\d{2}$")
    end_date: str = Field(..., pattern=r"^\d{4}-\d{2}-\d{2}$")
    travelers_count: int = Field(1, ge=1, le=50)
    traveler_type: str = Field("solo", pattern="^(solo|couple|family|friends|business)$")
    budget_level: str = Field("moderate", pattern="^(budget|moderate|luxury)$")
    currency: str = Field("USD", min_length=3, max_length=3)
    pace: str = Field("moderate", pattern="^(relaxed|moderate|fast-paced)$")
    interests: List[str] = Field(default_factory=list)
    accommodation_type: Optional[str] = "hotel"
    transport_preference: Optional[str] = "mixed"
    dietary_requirements: List[str] = Field(default_factory=list)
    accessibility_needs: Optional[str] = None
    notes: Optional[str] = None

class BudgetBreakdownCategory(BaseModel):
    category: str
    estimated_amount: float
    percentage: float
    description: str

class BudgetBreakdown(BaseModel):
    total_estimated: float
    per_person_estimated: float
    daily_average: float
    currency: str
    is_live_estimate: bool = False
    disclaimer: str = "Estimates are AI-generated approximations based on regional averages and travel style. Actual costs may vary."
    categories: List[BudgetBreakdownCategory] = []

class PracticalTip(BaseModel):
    category: str  # transport, safety, etiquette, weather, currency
    title: str
    content: str

class AccommodationRecommendation(BaseModel):
    name: str
    neighborhood: str
    style: str
    price_tier: str
    estimated_nightly_cost: float
    why_recommended: str

class GeneratedDay(BaseModel):
    day_number: int
    date: str
    title: str
    theme: str
    notes: Optional[str] = None
    daily_estimated_cost: float
    activities: List[ActivityBase]

class GeneratedItineraryResponse(BaseModel):
    trip_title: str
    destination: str
    summary: str
    start_date: str
    end_date: str
    total_days: int
    currency: str
    cover_image_url: Optional[str] = None
    days: List[GeneratedDay]
    budget_summary: BudgetBreakdown
    practical_tips: List[PracticalTip]
    accommodation_suggestions: List[AccommodationRecommendation]
    assumptions_and_disclaimers: List[str]
    generation_source: str = Field(
        ...,
        description="'ai_model' if generated by LLM, or 'fallback_engine' if deterministic fallback"
    )
    provider_details: Optional[Dict[str, Any]] = None

class RegenerateDayRequest(BaseModel):
    destination: str
    day_number: int
    date: str
    trip_summary: Optional[str] = None
    existing_day_theme: Optional[str] = None
    travelers_count: int = 1
    traveler_type: str = "solo"
    budget_level: str = "moderate"
    currency: str = "USD"
    pace: str = "moderate"
    interests: List[str] = []
    dietary_requirements: List[str] = []
    accessibility_needs: Optional[str] = None
    refinement_instruction: Optional[str] = None

class RegenerateActivityRequest(BaseModel):
    destination: str
    activity_category: str
    time_slot: str
    current_activity_title: str
    budget_level: str = "moderate"
    currency: str = "USD"
    interests: List[str] = []
    refinement_instruction: Optional[str] = None
